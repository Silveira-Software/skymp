class Handler
{
public:
  bool matches = true;
  std::function<void()> enter = [] {};
  bool Matches(uint32_t, const std::string&) { return matches; }
};
#include "../src/platform_se/skyrim_platform/Hook.h"
#include "../src/platform_se/skyrim_platform/HookHandlerBlocker.h"
class SkyrimPlatform
{
public:
  static SkyrimPlatform* GetSingleton()
  {
    static SkyrimPlatform value;
    return &value;
  }
  bool failQueue = false, failPush = false;
  std::vector<std::function<void(Napi::Env)>> tasks;
  void AddUpdateTask(std::function<void(Napi::Env)> task)
  {
    if (failQueue)
      throw std::runtime_error("queue failure");
    tasks.push_back(task);
  }
  void PushAndWait(std::function<void(Napi::Env)> task)
  {
    if (failPush)
      throw std::runtime_error("dispatch failure");
    task({});
  }
  void Drain()
  {
    while (!tasks.empty()) {
      auto task = tasks.front();
      tasks.erase(tasks.begin());
      task({});
    }
  }
};
// Generated byte-for-byte from Hook.cpp by tools/test-hook-scope-windows.py.
#include "HookMethods.inc"
void Hook::HandleEnter(DWORD, uint32_t selfId, std::string& eventName,
                       const Napi::Env&)
{
  for (const auto& [id, handler] : handlers) {
    (void)id;
    if (handler->Matches(selfId, eventName))
      handler->enter();
  }
}
void Hook::HandleLeave(DWORD, bool, Napi::Env)
{
}
namespace {
void Require(bool value, const char* why)
{
  if (!value)
    throw std::runtime_error(why);
}
void Available(Hook& hook)
{
  const auto id = hook.AddHandler(std::make_shared<Handler>());
  hook.RemoveHandler(id);
}
template <class F>
void Throws(F fn, const char* expected)
{
  try {
    fn();
  } catch (const std::exception& e) {
    Require(std::string(e.what()).find(expected) != std::string::npos,
            "unexpected exception");
    return;
  }
  throw std::runtime_error("expected exception missing");
}
}
int main()
{
  try {
    auto* queue = SkyrimPlatform::GetSingleton();
    std::string event = "OnRaceSwitchComplete";
    {
      Hook hook("sendPapyrusEvent", "papyrusEventName", std::nullopt);
      hook.Enter(0x14, event);
      hook.Leave(true);
      Available(hook);
    }
    {
      Hook hook("sendPapyrusEvent", "papyrusEventName", std::nullopt);
      auto handler = std::make_shared<Handler>();
      handler->matches = false;
      hook.AddHandler(handler);
      hook.Enter(0x14, event);
      hook.Leave(true);
      Require(queue->tasks.empty(), "unmatched event queued");
      Available(hook);
    }
    {
      Hook hook("sendPapyrusEvent", "papyrusEventName", std::nullopt);
      auto handler = std::make_shared<Handler>();
      bool called = false;
      const auto id = hook.AddHandler(handler);
      handler->enter = [&] {
        called = true;
        Throws([&] { Available(hook); }, "inside hook context");
        Throws([&] { hook.RemoveHandler(id); }, "inside hook context");
      };
      hook.Enter(0x14, event);
      hook.Leave(true);
      Require(!called && queue->tasks.size() == 1,
              "callback was not deferred");
      Available(hook);
      queue->Drain();
      Require(called, "callback missing");
      Available(hook);
      hook.RemoveHandler(id);
    }
    {
      Hook hook("sendPapyrusEvent", "papyrusEventName", std::nullopt);
      auto handler = std::make_shared<Handler>();
      handler->enter = [] { throw std::runtime_error("callback failure"); };
      hook.AddHandler(handler);
      hook.Enter(0x14, event);
      Throws([&] { queue->Drain(); }, "callback failure");
      Available(hook);
    }
    {
      Hook hook("sendPapyrusEvent", "papyrusEventName", std::nullopt);
      hook.AddHandler(std::make_shared<Handler>());
      queue->failQueue = true;
      Throws([&] { hook.Enter(0x14, event); }, "queue failure");
      queue->failQueue = false;
      Available(hook);
    }
    {
      Hook hook("sendAnimationEvent", "animEventName", "animationSucceeded");
      queue->failPush = true;
      Throws([&] { hook.Enter(0x14, event); }, "dispatch failure");
      queue->failPush = false;
      Available(hook);
    }
    {
      Hook hook("sendAnimationEvent", "animEventName", "animationSucceeded");
      auto handler = std::make_shared<Handler>();
      handler->enter = [] { throw std::runtime_error("callback failure"); };
      hook.AddHandler(handler);
      hook.Enter(0x14, event);
      Available(hook);
      Throws([&] { queue->Drain(); }, "callback failure");
      hook.Leave(true);
      Available(hook);
    }
    {
      Hook hook("sendAnimationEvent", "animEventName", "animationSucceeded");
      hook.Enter(0x14, event);
      queue->failPush = true;
      Throws([&] { hook.Leave(true); }, "dispatch failure");
      queue->failPush = false;
      Available(hook);
    }
    std::cout << "{\"status\":\"PASS\",\"checks\":8,\"productionHookMethods\":"
                 "true,\"realSkyrim\":false}\n";
    return 0;
  } catch (const std::exception& e) {
    std::cerr << e.what() << '\n';
    return 1;
  }
}
